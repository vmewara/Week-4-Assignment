Q1 = df['profit'].quantile(0.25)
Q3 = df['profit'].quantile(0.75)

IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

df = df[(df['profit'] >= lower_bound) & (df['profit'] <= upper_bound)]

